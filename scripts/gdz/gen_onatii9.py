def lesson_of(n):
    for i, (a, b, _, _) in enumerate(LESSONS):
        if a <= n <= b:
            return i
    raise SystemExit(f'урок {n} не знайдено в ЗМІСТі')


def lesson_label(i):
    a, b, t, _ = LESSONS[i]
    return (f'Урок {a}' if a == b else f'Уроки {a}–{b}') + '. ' + t


# 1) зміст.html: id → розділ
zm = open(ZM, encoding='utf-8').read().split('<body>', 1)[1]
order, rozdil_of = [], {}
cur = None
for m in re.finditer(r'<h2[^>]*>(.*?)</h2>|<a href="готово/([^"]+)\.html"', zm, re.S):
    if m.group(1) is not None:
        cur = html.unescape(re.sub(r'<[^>]+>', '', m.group(1))).strip()
        assert cur in dict(ROZDILY), f'невідомий розділ у зміст.html: {cur!r}'
        continue
    order.append(m.group(2))
    rozdil_of[m.group(2)] = cur

# 2) урок кожної вправи — з html
les = {}
for x in order:
    if x in MULTI:
        les[x] = lesson_of(MULTI[x])
        continue
    t = open(f'{SRC}/готово/{x}.html', encoding='utf-8').read()
    top = re.search(r'class="gdz9-page-topic"[^>]*>(.*?)</div>', t, re.S)
    n = int(re.search(r'Урок[иі]?\s*(\d+)', re.sub(r'<[^>]+>', '', top.group(1))).group(1))
    les[x] = lesson_of(n)

# перевірки: уроки вправ не спадають; розділ уроку = розділ у зміст.html
vprs = sorted((x for x in order if x.startswith('vpr-')), key=lambda x: int(x[4:]))
assert [int(x[4:]) for x in vprs] == list(range(1, len(vprs) + 1)), 'вправи не наскрізні'
for a, b in zip(vprs, vprs[1:]):
    assert les[a] <= les[b], f'урок іде назад: {a} ({lesson_label(les[a])}) → {b} ({lesson_label(les[b])})'
names = [h for h, _ in ROZDILY]
for x in order:
    assert names[LESSONS[les[x]][3]] == rozdil_of[x], f'{x}: зміст.html каже «{rozdil_of[x]}», урок — «{names[LESSONS[les[x]][3]]}»'


def file_of(x):
    return x[4:] if x.startswith('vpr-') else x


def stor_label(x):
    a, b = re.search(r'stor-(\d+)-(\d+)$', x).groups()
    return f'Стор. {a}–{b}'


# 3) розділ → урок → кнопки (вправи — за номером, тести/КПР — на місці свого уроку)
