def js(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'") + "'"


def compress(ns):
    out, i = [], 0
    while i < len(ns):
        j = i
        while j + 1 < len(ns) and ns[j + 1] == ns[j] + 1:
            j += 1
        if j - i >= 2:
            out.append(f'...range({ns[i]}, {ns[j]})')
        else:
            out.extend(str(v) for v in ns[i:j + 1])
        i = j + 1
    return ', '.join(out)


