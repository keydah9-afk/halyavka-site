LAST_PAGE = 202  # с. 203 — словник наголосів

def par_of(page):
    cur = None
    for p in PARS:
        if p[2] <= page:
            cur = p
    assert cur and page <= LAST_PAGE, page
    return cur

src = open(ZM, encoding='utf-8').read().split('<body>', 1)[1]

# розділ → [сторінки] у порядку зміста; назва розділу: «Вступ (§ 1)» → «Вступ»
blocks = []
for m in re.finditer(r'<h2[^>]*>(.*?)</h2>|<a href="готово/stor-(\d+)\.html"', src, re.S):
    if m.group(1) is not None:
        name = html.unescape(re.sub(r'<[^>]+>', '', m.group(1))).strip()
        rng = re.search(r'\(§\s*([\d–-]+)\)', name)
        name = re.sub(r'\s*\(§[^)]*\)\s*$', '', name).strip()
        blocks.append((name, rng.group(1) if rng else None, []))
        continue
    blocks[-1][2].append(int(m.group(2)))

real = {int(f[:-5]) for f in os.listdir(IMGDIR) if re.fullmatch(r'\d+\.webp', f)}
junk = [f for f in os.listdir(IMGDIR) if not re.fullmatch(r'\d+\.webp', f)]

# діапазон § у назві розділу зміста має збігатися з тим, куди сторінки лягли за друкованим ЗМІСТом
for name, rng, pages in blocks:
    pars = [par_of(n)[0] for n in pages]
    lo = pars[0].split('–')[0]
    hi = pars[-1].split('–')[-1]
    want = rng.replace('-', '–').split('–')
    assert (lo, hi) == (want[0], want[-1]), f'{name}: зміст каже § {rng}, за сторінками § {lo}–{hi}'

flat = [n for _, _, pages in blocks for n in pages if n in real]
print('buttons:', len(flat), 'uniq:', len(set(flat)), 'real files:', len(real))
print('missingButtons (файл є, кнопки нема):', sorted(real - set(flat)))
print('extraButtons  (кнопка є, файлу нема):', sorted({n for _, _, p in blocks for n in p} - real))
print('dups:', len(flat) - len(set(flat)))
print('інші файли в теці:', junk)

